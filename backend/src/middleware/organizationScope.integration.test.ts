import test from 'node:test';
import assert from 'node:assert/strict';
import express from 'express';
import { once } from 'node:events';
import { randomUUID } from 'node:crypto';
import { eq } from 'drizzle-orm';
import { db, closeDatabase } from '../db';
import { roles, users, rolePermissions, permissions } from '../db/schema/users';
import { organizationGroups, userOrganizationGroupAccess } from '../db/schema/organizations';
import { generateToken } from '../utils/jwt';
import { authenticateToken, requirePermission } from './auth';
import { requireOrganizationScope, type OrganizationScopedRequest } from './organizationScope';
import { me } from '../controllers/authController';
import { postAttendanceCommand } from '../controllers/attendanceCommandController';

test('HTTP scope combines current permission and membership, validates write destinations, and exposes only available groups', async t => {
  await db.insert(organizationGroups).values([{code: 'CMC', name: 'CMC'}, {code: 'MGM', name: 'MGM'}]).onConflictDoNothing();
  const groups = await db.select().from(organizationGroups);
  const cmc = groups.find(g => g.code === 'CMC')!.id;
  const mgm = groups.find(g => g.code === 'MGM')!.id;
  const [role] = await db.insert(roles).values({code: `scope_test_${Date.now()}`, name: `Scoped test ${Date.now()}`}).returning();
  const [user] = await db.insert(users).values({username: `scope-http-${Date.now()}`, passwordHash: 'unused', roleId: role.id, role: 'Employee'}).returning();
  await db.insert(userOrganizationGroupAccess).values({userId: user.id, groupId: cmc});
  const [permission] = await db.select().from(permissions).where(eq(permissions.code, 'ga.requests.view'));
  const app = express();
  app.use(express.json(), authenticateToken);
  app.get('/me', me);
  app.post('/commands',requirePermission('attendance.manage'),requireOrganizationScope('hr','write'),postAttendanceCommand);
  app.get('/scope', requirePermission('ga.requests.view'), requireOrganizationScope('ga','read'), (req: OrganizationScopedRequest,res) => res.json(req.organizationScope));
  app.post('/scope', requirePermission('ga.requests.view'), requireOrganizationScope('ga','write'), (req: OrganizationScopedRequest,res) => res.json(req.organizationScope));
  const server = app.listen(0,'127.0.0.1');
  await once(server,'listening');
  t.after(async () => {
    await new Promise<void>(resolve => server.close(() => resolve()));
    await db.delete(userOrganizationGroupAccess).where(eq(userOrganizationGroupAccess.userId,user.id));
    await db.delete(users).where(eq(users.id,user.id));
    await db.delete(rolePermissions).where(eq(rolePermissions.roleId,role.id));
    await db.delete(roles).where(eq(roles.id,role.id));
    await closeDatabase();
  });
  const token = generateToken({userId: user.id, roleId: role.id, roleName: 'SuperAdmin'});
  const base = `http://127.0.0.1:${(server.address() as {port:number}).port}`;
  const api = (path: string, selection?: string, body?: unknown) => fetch(base+path, {method: body === undefined ? 'GET' : 'POST',
    headers: {Authorization: `Bearer ${token}`, 'Content-Type': 'application/json', ...(selection === undefined ? {} : {'X-Organization-Group-Id': selection})},
    body: body === undefined ? undefined : JSON.stringify(body)});
  assert.equal((await api('/scope',String(cmc))).status,403, 'membership does not grant permission');
  await db.insert(rolePermissions).values({roleId: role.id, permissionId: permission.id});
  assert.equal((await api('/scope',String(mgm))).status,403);
  assert.equal((await api('/scope','1e2')).status,400);
  let result = await api('/scope');
  assert.equal(result.status,200);
  assert.deepEqual(await result.json(), {module:'ga',groupIds:[cmc],selectedGroupId:cmc,includeUnmapped:false});
  const account = await (await api('/me')).json();
  assert.deepEqual(account.user.organizationAccess, {groupIds:[cmc],isGlobalAdministrator:false});
  assert.deepEqual(account.user.availableGroups.map((g: {id:number}) => g.id), [cmc]);
  assert.equal((await api('/scope',String(cmc),{groupId:mgm})).status,400);
  await db.insert(userOrganizationGroupAccess).values({userId:user.id,groupId:mgm});
  assert.equal((await api('/scope',undefined,{})).status,400);
  result = await api('/scope',String(mgm),{groupId:mgm});
  assert.equal(result.status,200);
  assert.equal((await result.json()).selectedGroupId,mgm);
  await db.delete(userOrganizationGroupAccess).where(eq(userOrganizationGroupAccess.userId,user.id));
  assert.equal((await api('/scope',String(cmc))).status,403, 'revocation takes effect with same token');
  const [attendancePermission] = await db.select().from(permissions).where(eq(permissions.code,'attendance.manage'));
  await db.insert(rolePermissions).values({roleId:role.id,permissionId:attendancePermission.id});
  const command = {operationId:randomUUID(),command:{type:'lock',workDate:'2099-10-29',locked:true,reason:'Disposable scope authentication regression'}};
  const [administratorRole]=await db.select().from(roles).where(eq(roles.code,'super_admin'));
  await db.update(users).set({roleId:administratorRole.id,role:administratorRole.name}).where(eq(users.id,user.id));
  result = await api('/commands',String(cmc),command);
  assert.equal(result.status,200,'current permissions must reach attendance command authorization');
  await db.delete(rolePermissions).where(eq(rolePermissions.roleId,role.id));
  await db.update(users).set({roleId:role.id,role:role.name}).where(eq(users.id,user.id));
  result = await api('/commands',String(cmc),{...command,operationId:randomUUID()});
  assert.equal(result.status,403,'same JWT loses revoked command permission immediately');
});
