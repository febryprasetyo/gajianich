import { requireOrganizationScope } from '../middleware/organizationScope';
import { Router } from 'express';
import { authenticateToken, requireRoles } from '../middleware/auth';
import { getCustodians, postCustodian, patchCustodian, resolveEmployee, linkEmployee, mergeCustodian, getReconciliationCandidates, getCustodianAssetsHandler } from '../controllers/assetCustodianController';
const router = Router();
router.use(authenticateToken);
const admin = requireRoles('SuperAdmin', 'ITAdmin');
const lifecycle = requireRoles('SuperAdmin', 'ITAdmin', 'ITStaff');
router.get('/', lifecycle, requireOrganizationScope('assets', 'read'), getCustodians);
router.get('/reconciliation-candidates', admin, requireOrganizationScope('assets', 'read'), getReconciliationCandidates);
router.get('/:id/assets', lifecycle, requireOrganizationScope('assets', 'read'), getCustodianAssetsHandler);
router.post('/resolve-employee', lifecycle, requireOrganizationScope('assets', 'write'), resolveEmployee);
router.post('/', admin, requireOrganizationScope('assets', 'write'), postCustodian);
router.patch('/:id', admin, requireOrganizationScope('assets', 'write'), patchCustodian);
router.post('/:id/link-employee', admin, requireOrganizationScope('assets', 'write'), linkEmployee);
router.post('/:id/merge', admin, requireOrganizationScope('assets', 'write'), mergeCustodian);
export default router;
